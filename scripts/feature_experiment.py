"""Feature experiment: do the 4 new SQL features (discharge_group, comorbidity_count,
frequent_flyer, emergency_repeat) improve the model?

Decided with 5-fold patient-grouped cross-validation on TRAIN+VAL only. The test set is never
touched here, so choosing features cannot leak test information into the final numbers.

Usage:  python -m scripts.feature_experiment
Writes: reports/feature_experiment.md
"""
import numpy as np
import pandas as pd
from sklearn.metrics import average_precision_score, roc_auc_score
from sklearn.model_selection import GroupKFold

from src.config import (CATEGORICAL_FEATURES, FEATURES_PARQUET, GROUP_COL, NUMERIC_FEATURES,
                        REPORTS_DIR, TARGET)
from src.train import grouped_split, train_logistic, train_xgboost

NEW_NUMERIC = ["comorbidity_count", "frequent_flyer", "emergency_repeat"]
NEW_CATEGORICAL = ["discharge_group"]

CONFIGS = {
    "Original features": (NUMERIC_FEATURES, CATEGORICAL_FEATURES),
    "+ 4 new features": (NUMERIC_FEATURES + NEW_NUMERIC, CATEGORICAL_FEATURES + NEW_CATEGORICAL),
    "+ discharge_group replaces raw discharge codes": (
        NUMERIC_FEATURES + NEW_NUMERIC,
        [c for c in CATEGORICAL_FEATURES if c != "discharge_disposition"] + NEW_CATEGORICAL),
}


def main():
    df = pd.read_parquet(FEATURES_PARQUET).reset_index(drop=True)
    train, val, _test = grouped_split(df)            # same split as src/train.py
    dev = pd.concat([train, val]).reset_index(drop=True)

    rows = []
    for fold, (tr_idx, va_idx) in enumerate(GroupKFold(n_splits=5).split(dev, groups=dev[GROUP_COL])):
        tr, va = dev.iloc[tr_idx], dev.iloc[va_idx]
        # hold out 10% of the training fold's patients for XGBoost early stopping
        pats = tr[GROUP_COL].unique()
        es_pats = set(np.random.default_rng(fold).choice(pats, size=len(pats) // 10, replace=False))
        es_mask = tr[GROUP_COL].isin(es_pats)
        for name, (num, cat) in CONFIGS.items():
            prep, model = train_xgboost(tr[~es_mask], tr[es_mask], num, cat)
            p_x = model.predict_proba(prep.transform(va[num + cat]))[:, 1]
            lr = train_logistic(tr, num, cat)
            p_l = lr.predict_proba(va[num + cat])[:, 1]
            y = va[TARGET]
            rows.append({"fold": fold + 1, "config": name,
                         "xgb_auroc": roc_auc_score(y, p_x), "xgb_pr_auc": average_precision_score(y, p_x),
                         "lr_auroc": roc_auc_score(y, p_l), "lr_pr_auc": average_precision_score(y, p_l)})
            print(f"fold {fold + 1} | {name:48s} XGB AUROC {rows[-1]['xgb_auroc']:.4f} | "
                  f"LR AUROC {rows[-1]['lr_auroc']:.4f}")

    res = pd.DataFrame(rows)
    res.to_csv(REPORTS_DIR / "feature_experiment_folds.csv", index=False)

    # paired differences vs the original features, fold by fold
    base = res[res.config == "Original features"].set_index("fold")
    summary = []
    for name in CONFIGS:
        r = res[res.config == name].set_index("fold")
        row = {"config": name}
        for m in ["xgb_auroc", "xgb_pr_auc", "lr_auroc", "lr_pr_auc"]:
            d = r[m] - base[m]
            row[m] = f"{r[m].mean():.4f} ± {r[m].std():.4f}"
            row[f"Δ {m}"] = "-" if name == "Original features" else \
                f"{d.mean():+.4f} ({(d > 0).sum()}/5 folds better)"
        summary.append(row)
    s = pd.DataFrame(summary)
    md = ["# Feature experiment (auto-generated by `python -m scripts.feature_experiment`)", "",
          f"5-fold patient-grouped cross-validation on train+val ({len(dev):,} encounters). Test set untouched.",
          "Δ = mean paired difference vs original features across the same 5 folds.", "",
          s.to_markdown(index=False), ""]
    (REPORTS_DIR / "feature_experiment.md").write_text("\n".join(md))
    print("\n" + s.to_string(index=False))


if __name__ == "__main__":
    main()
