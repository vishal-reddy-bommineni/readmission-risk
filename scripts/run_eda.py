"""Run sql/eda.sql against the DuckDB database and write reports/eda.md.

Usage:  python -m scripts.run_eda      (run src.build_features first)
"""
import csv
import io

import duckdb
import pandas as pd

from src.config import DB_PATH, REPORTS_DIR, ROOT

MAPPING_CSV = ROOT / "data" / "raw" / "IDS_mapping.csv"


def load_mappings(con):
    """IDS_mapping.csv holds three small tables stacked in one file, separated by blank rows."""
    if not MAPPING_CSV.exists():
        con.execute("CREATE OR REPLACE TABLE discharge_map (id INTEGER, description VARCHAR)")
        print("IDS_mapping.csv not found - discharge descriptions will be blank")
        return
    blocks, current = [], []
    for row in csv.reader(io.StringIO(MAPPING_CSV.read_text())):
        if not any(cell.strip() for cell in row):
            if current:
                blocks.append(current)
            current = []
        else:
            current.append(row[:2])
    if current:
        blocks.append(current)
    for block in blocks:
        table = {"admission_type_id": "admission_type_map",
                 "discharge_disposition_id": "discharge_map",
                 "admission_source_id": "admission_source_map"}[block[0][0]]
        df = pd.DataFrame(block[1:], columns=["id", "description"])
        df["id"] = pd.to_numeric(df["id"], errors="coerce").astype("Int64")
        con.register("tmp_map", df)
        con.execute(f"CREATE OR REPLACE TABLE {table} AS SELECT * FROM tmp_map")
        con.unregister("tmp_map")


def main():
    con = duckdb.connect(str(DB_PATH))
    load_mappings(con)
    sql = (ROOT / "sql" / "eda.sql").read_text()
    out = ["# Exploratory analysis (auto-generated by `python -m scripts.run_eda`)", "",
           "Queries: `sql/eda.sql`. Cohort = encounters after removing expired/hospice discharges.", ""]
    for chunk in sql.split("-- name:")[1:]:
        title, query = chunk.split("\n", 1)
        df = con.execute(query.strip().rstrip(";")).df()
        out += [f"## {title.strip()}", "", df.to_markdown(index=False), ""]
        print(f"\n== {title.strip()}\n{df.to_string(index=False)}")
    (REPORTS_DIR / "eda.md").write_text("\n".join(out))
    con.close()


if __name__ == "__main__":
    main()
